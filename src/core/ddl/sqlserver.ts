// SQL Server DDL from a PDM: CREATE TABLE with PK / UNIQUE / CHECK, then FKs as ALTER TABLE
// (so table order never matters, cycles included) — the same layout PowerDesigner generates.

import type { PdmColumn, PdmTable, Pdm } from '../pdm'

export interface SqlServerOptions {
  /** Prepend DROP statements so the script can be re-run on the same database. */
  drop?: boolean
}

/** Conceptual type → SQL Server type (PowerDesigner's mapping for SQL Server). */
export function sqlServerType(c: Pick<PdmColumn, 'dataType' | 'length' | 'precision'>): string {
  switch (c.dataType) {
    case 'Integer':
      return 'int'
    case 'Short integer':
      return 'smallint'
    case 'Long integer':
      return 'bigint'
    case 'Decimal':
      return c.length !== undefined ? `decimal(${c.length}${c.precision !== undefined ? `,${c.precision}` : ''})` : 'decimal(18,2)'
    case 'Float':
      return 'float'
    case 'Money':
      return 'money'
    case 'Boolean':
      return 'bit'
    case 'Characters':
      return `char(${c.length ?? 1})`
    case 'Variable characters':
      return c.length !== undefined ? `varchar(${c.length})` : 'varchar(max)'
    case 'Text':
      return 'varchar(max)'
    case 'Date':
      return 'date'
    case 'Time':
      return 'time'
    case 'Date & time':
      return 'datetime'
    case 'Binary':
      return c.length !== undefined ? `varbinary(${c.length})` : 'varbinary(max)'
  }
}

