/** Brackets identifiers that are reserved words or not plain `[A-Za-z_][A-Za-z0-9_]*`. */
export function quoteIdent(name: string): string {
  if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(name) && !RESERVED.has(name.toUpperCase())) return name
  return `[${name.replace(/]/g, ']]')}]`
}

const list = (cols: string[]) => cols.map(quoteIdent).join(', ')

function comment(text: string): string {
  return text
    .split('\n')
    .map((l) => `-- ${l}`.trimEnd())
    .join('\n')
}

function createTable(t: PdmTable): string {
  const width = Math.max(20, ...t.columns.map((c) => quoteIdent(c.name).length + 1))
  const typeWidth = Math.max(16, ...t.columns.map((c) => sqlServerType(c).length + 1))
  const lines = t.columns.map(
    (c) => `   ${quoteIdent(c.name).padEnd(width)} ${sqlServerType(c).padEnd(typeWidth)} ${c.nullable ? 'NULL' : 'NOT NULL'}`,
  )
  if (t.primaryKey) lines.push(`   CONSTRAINT ${quoteIdent(t.primaryKey.name)} PRIMARY KEY (${list(t.primaryKey.columns)})`)
  for (const ak of t.alternateKeys) lines.push(`   CONSTRAINT ${quoteIdent(ak.name)} UNIQUE (${list(ak.columns)})`)
  for (const ck of t.checks) lines.push(`   CONSTRAINT ${quoteIdent(ck.name)} CHECK (${ck.expression})`)
  const head = [`-- Table ${t.name}`]
  if (t.comment) head.push(comment(t.comment))
  return `${head.join('\n')}\nCREATE TABLE ${quoteIdent(t.name)} (\n${lines.join(',\n')}\n)\nGO`
}

export function generateSqlServer(pdm: Pdm, opts: SqlServerOptions = {}): string {
  const out: string[] = [comment(`SQL Server DDL for "${pdm.name}" — generated by StrataSQL from the conceptual model.`)]
  const fks = pdm.tables.flatMap((t) => t.foreignKeys.map((fk) => ({ t, fk })))

  if (opts.drop) {
    const drops = fks.map(
      ({ t, fk }) =>
        `IF OBJECT_ID('${fk.name.replace(/'/g, "''")}', 'F') IS NOT NULL\n   ALTER TABLE ${quoteIdent(t.name)} DROP CONSTRAINT ${quoteIdent(fk.name)}\nGO`,
    )
    drops.push(...pdm.tables.map((t) => `DROP TABLE IF EXISTS ${quoteIdent(t.name)}\nGO`))
    out.push(`${comment('Drop the previous version (FKs first, so tables can go in any order)')}\n${drops.join('\n\n')}`)
  }

  out.push(...pdm.tables.map(createTable))

  for (const { t, fk } of fks)
    out.push(
      `ALTER TABLE ${quoteIdent(t.name)}\n   ADD CONSTRAINT ${quoteIdent(fk.name)} FOREIGN KEY (${list(fk.columns)})\n` +
        `      REFERENCES ${quoteIdent(fk.refTable)} (${list(fk.refColumns)})\nGO`,
    )
  return out.join('\n\n') + '\n'
}
