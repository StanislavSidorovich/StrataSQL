import { describe, expect, it } from 'vitest'
import { generatePdm } from '../src/core/cdm2pdm'
import { generatePostgres } from '../src/core/ddl/postgres'
import { generateSqlServer } from '../src/core/ddl/sqlserver'
import { exportPowerDesigner } from '../src/core/export/powerdesigner'
import { exportPowerDesignerPdm } from '../src/core/export/powerdesigner-pdm'
import { importPowerDesigner, parsePdType } from '../src/core/import/powerdesigner'
import { readPdTables } from '../src/core/import/pdm-reader'
import { readSqlScript } from '../src/core/import/sql-reader'
import { emptyModel } from '../src/core/metamodel'
import { addAttribute, addEntity, addRelationship } from '../src/core/ops'
import { parseModel, serializeModel } from '../src/core/serialize'

function build() {
  const m = emptyModel('Serial')
  const a = addEntity(m, { name: 'Customer' })
  const b = addEntity(m, { name: 'Orders', position: { x: 300, y: 0 } })
  addAttribute(m, a.id, { name: 'customer_id', dataType: 'Serial', primary: true })
  addAttribute(m, b.id, { name: 'order_no', dataType: 'Integer', primary: true })
  addRelationship(m, a.id, b.id)
  return m
}

describe('Serial (autonumbering)', () => {
  it('is IDENTITY in SQL Server and PostgreSQL, and a foreign key stays a plain integer', () => {
    const pdm = generatePdm(build())
    const orders = pdm.tables.find((t) => t.name.toUpperCase() === 'ORDERS')!
    expect(orders.columns.find((c) => c.migrated)!.dataType).toBe('Integer')
    expect(generateSqlServer(pdm)).toMatch(/customer_id\s+int identity\s+NOT NULL/)
    expect(generateSqlServer(pdm)).not.toMatch(/customer_id\s+int\s+NOT NULL[^]*customer_id\s+int identity/)
    expect(generatePostgres(pdm)).toMatch(/customer_id\s+integer generated by default as identity\s+NOT NULL/)
  })
  it('survives .strata.json, .cdm and .pdm', () => {
    const m = build()
    expect(parseModel(serializeModel(m)).entities[0].attributes[0].dataType).toBe('Serial')
    const cdm = exportPowerDesigner(m).xml
    expect(cdm).toContain('<a:DataType>NO</a:DataType>')
    expect(importPowerDesigner(cdm, 'x.cdm').model.entities.find((e) => e.name === 'Customer')!.attributes[0].dataType).toBe('Serial')
    expect(parsePdType('NO')).toEqual({ dataType: 'Serial' })
    const pdm = exportPowerDesignerPdm(m).xml
    expect(pdm).toContain('<a:Identity>1</a:Identity>')
    const cols = readPdTables(pdm).find((t) => t.code.toUpperCase() === 'CUSTOMER')!.columns
    expect(cols[0].type).toBe('int identity')
  })
  it('is read back from SQL', () => {
    const { tables } = readSqlScript(
      'CREATE TABLE a (id int IDENTITY(1,1) PRIMARY KEY, n int);\nCREATE TABLE b (id serial PRIMARY KEY, n int AUTO_INCREMENT);\nCREATE TABLE c (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);',
    )
    expect(tables.map((t) => t.columns.map((c) => c.sqlType.dataType))).toEqual([['Serial', 'Integer'], ['Serial', 'Serial'], ['Serial']])
  })
})
